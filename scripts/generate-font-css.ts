/**
 * Regenerates src/app/template-fonts.css from the font registry so browsers
 * load exactly the same font files the export engine uses.
 * Run: npm run fonts:css   (after adding a font to src/lib/rendering/fonts.ts)
 */
import fs from "node:fs";
import path from "node:path";
import { FALLBACK_FONT_CSS_NAME, FALLBACK_FONT_FILE, FONT_FAMILIES } from "../src/lib/rendering/fonts";

let css = "/* Template fonts (SIL Open Font License). Generated by scripts/generate-font-css.ts — do not edit by hand. */\n";
for (const family of Object.values(FONT_FAMILIES)) {
  for (const face of family.faces) {
    css += `@font-face {\n  font-family: "${family.cssName}";\n  src: url("/fonts/${face.file}") format("truetype");\n  font-weight: ${face.weight};\n  font-style: ${face.italic ? "italic" : "normal"};\n  font-display: swap;\n}\n`;
  }
}
css += `@font-face {\n  font-family: "${FALLBACK_FONT_CSS_NAME}";\n  src: url("/fonts/${FALLBACK_FONT_FILE}") format("truetype");\n  font-weight: 400;\n  font-display: swap;\n  unicode-range: U+0900-097F, U+1CD0-1CFF, U+A8E0-A8FF;\n}\n`;
fs.writeFileSync(path.join(process.cwd(), "src", "app", "template-fonts.css"), css);
console.log("Wrote src/app/template-fonts.css");
