/**
 * Generates supabase/seed.sql from the categories and the 16 starter
 * templates defined in code. The SQL is safe to run repeatedly:
 *   - categories are upserted by slug;
 *   - templates are inserted once by slug and never overwrite a template an
 *     administrator has since edited (the version check below).
 *
 * Run: npm run db:seed:generate
 */
import fs from "node:fs";
import path from "node:path";
import { CATEGORIES } from "../src/lib/templates/categories";
import { STARTER_TEMPLATES } from "../src/templates/starter";
import { FORMAT_IDS, templateDefinitionSchema } from "../src/lib/templates/schema";

const OUT = path.join(process.cwd(), "supabase", "seed.sql");
const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const ASPECT = { portrait: "9:16", square: "1:1", landscape: "16:9" } as const;

let sql = `-- Celebrio seed data (generated by scripts/generate-seed.ts — do not edit by hand)
-- Safe to re-run: it never duplicates categories or starter templates.

begin;

`;

for (const c of CATEGORIES) {
  sql += `insert into public.categories (name, slug, description, display_order, is_active)
values (${q(c.name)}, ${q(c.slug)}, ${q(c.description)}, ${c.displayOrder}, true)
on conflict (slug) do update set name = excluded.name, description = excluded.description, display_order = excluded.display_order;

`;
}

for (const t of STARTER_TEMPLATES) {
  const def = templateDefinitionSchema.parse(t.definition);
  const formats = FORMAT_IDS.filter((f) => def.formats[f]);
  sql += `insert into public.templates (category_id, name, slug, description, tags, style, color_family, preview_path, template_definition, supported_formats, aspect_ratio, price_amount, multi_format_price_amount, currency, is_free, is_published, version, published_at)
select c.id, ${q(t.name)}, ${q(t.slug)}, ${q(t.description)}, array[${t.tags.map(q).join(", ")}]::text[], ${q(t.style)}, ${q(t.colorFamily)},
       ${q(`/templates/previews/${t.slug}-${def.defaultFormat}.webp`)}, ${q(JSON.stringify(def))}::jsonb, array[${formats.map(q).join(", ")}]::text[], ${q(ASPECT[def.defaultFormat])},
       ${t.priceAmount}, ${t.multiFormatPriceAmount ?? "null"}, 'INR', ${t.isFree}, true, 1, now()
from public.categories c where c.slug = ${q(t.category)}
on conflict (slug) do nothing;

`;
}

sql += "commit;\n";
fs.writeFileSync(OUT, sql);
console.log(`Wrote ${OUT} (${CATEGORIES.length} categories, ${STARTER_TEMPLATES.length} templates)`);
